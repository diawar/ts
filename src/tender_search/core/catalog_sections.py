class DeliveryRegion(Func):
    output_field = BooleanField()

    def __init__(self, prefix):
        super().__init__('search_meta', 'row')
        self.prefix = prefix

    def as_postgresql(self, compiler, connection, **extra_context):
        meta, meta_params = compiler.compile(self.source_expressions[0])
        sql, params = compiler.compile(self.source_expressions[1])
        path = f'$.delivery_addresses[*] ? (@.code like_regex "^{self.prefix}[0-9]{{7}}$")'
        compact_path = f'$.delivery_codes[*] ? (@ like_regex "^{self.prefix}[0-9]{{7}}$")'
        return (f"CASE WHEN {meta} ? 'delivery_codes' THEN jsonb_path_exists({meta}, %s) ELSE jsonb_path_exists({sql}, %s) END",
                [*meta_params, *meta_params, compact_path, *params, path])

    def as_sqlite(self, compiler, connection, **extra_context):
        sql, params = compiler.compile(self.source_expressions[1])
        return (f"EXISTS (SELECT 1 FROM json_each({sql}, '$.delivery_addresses') a "
                "WHERE CAST(json_extract(a.value, '$.code') AS TEXT) GLOB %s)",
                [*params, self.prefix+'[0-9]'*7])


class CatalogTitle(Func):
    output_field = TextField()

    def __init__(self):
        super().__init__('row')

    def as_postgresql(self, compiler, connection, **extra_context):
        sql, params = compiler.compile(self.source_expressions[0])
        return f"COALESCE(NULLIF({sql}->>'name_ru', ''), {sql}->>'name', '')", [*params, *params]

    def as_sqlite(self, compiler, connection, **extra_context):
        sql, params = compiler.compile(self.source_expressions[0])
        return f"COALESCE(NULLIF(json_extract({sql}, '$.name_ru'), ''), json_extract({sql}, '$.name'), '')", [*params, *params]


def section_filter(section):
    if section['kind'] == 'region':
        return Q(DeliveryRegion(section['prefix']))
    # Match word beginnings in lot titles only, never customer/description text.
    pattern = r'(^|[^а-яёa-z0-9])(' + '|'.join(section['stems']) + ')'
    return Q(catalog_title__iregex=pattern)


def active_section_paths():
    """Bounded existence checks stop at the first match; cached for five minutes."""
    key = 'public-catalog-sections-v1'
    paths = cache.get(key)
    if paths is None:
        from .catalog_views import public_lots
        paths = [section['path'] for section in SECTIONS if public_lots().filter(section_filter(section)).exists()]
        cache.set(key, paths, 300)
    return paths
